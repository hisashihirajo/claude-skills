#!/bin/sh
# UserPromptSubmit。入力のたびに「日本語で答える」と念を押す。
# 長いセッションの終盤や英語の資料を読んだあとに、返答が英語へ流れるのを防ぐ。
# 標準入力は読み捨てる（読まないと呼び出し側が詰まることがある）
cat >/dev/null
cat <<'MSG'
<system-reminder>
ユーザーへの回答・報告・質問・途中経過の一言は、必ず日本語で書いてください。英語で回答してはいけません。
識別子・コマンド・ファイル名・製品名は英語のままでかまいません。英文の成果物を頼まれた場合も、その説明や報告は日本語です。
</system-reminder>
MSG
exit 0
